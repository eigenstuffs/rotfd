"""Keep the exact legacy link object and write a corrected reporting copy.

MWLD requires DTK's nonzero synthetic function symbol even for this original
storage range. Only native objdiff uses the separately pinned metadata copy;
all section payloads and the complete original fallback unit remain identical.
"""

import argparse
import hashlib
import json
from pathlib import Path

if __package__:
    from .normalize_text_storage import normalize
else:
    from normalize_text_storage import normalize


def write_report_copy(original, target, contract):
    data = original.read_bytes()
    if hashlib.sha256(data).hexdigest() != contract["generated_sha256"]:
        raise ValueError("Link input must retain the exact generated storage object")
    corrected = normalize(data, contract)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_bytes() != corrected:
        target.write_bytes(corrected)
    return corrected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("build_dir", type=Path)
    parser.add_argument("--contract", type=Path, default=Path("config/GSQE78/text_storage.json"))
    args = parser.parse_args()
    contract = json.loads(args.contract.read_text())
    if (contract["schema"], contract["game_id"], contract["address"], contract["size"]) != (
            "original-text-storage-metadata-v1", "GSQE78", 0x801EF5C8, 44):
        raise ValueError("Unsupported original storage contract")
    config = json.loads((args.build_dir / "config.json").read_text())
    units = [u for u in config["units"] if u["name"] == contract["unit"]]
    if len(units) != 1 or not units[0]["autogenerated"]:
        raise ValueError("Expected the original generated storage fallback unit")
    target = args.build_dir / "obj-report" / (contract["unit"] + ".o")
    write_report_copy(Path(units[0]["object"]), target, contract)
    print("Preserved raw legacy link input; wrote identical-payload storage metadata copy for native objdiff")


if __name__ == "__main__":
    main()
