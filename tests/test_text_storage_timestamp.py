"""An unchanged split co-output must become current without changing its bytes."""

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

from test_text_storage import fixture
from tools.normalize_text_storage import normalize


class TextStorageTimestampTests(unittest.TestCase):
    def prepare(self, directory):
        build = Path(directory)
        data, contract, _, _ = fixture()
        contract.update(schema="original-text-storage-metadata-v1", game_id="GSQE78",
                        address=0x801EF5C8, unit="auto_03_801EF5C8_text")
        raw = build / "raw.o"
        raw.write_bytes(data)
        target = build / "obj-report/auto_03_801EF5C8_text.o"
        target.parent.mkdir()
        target.write_bytes(normalize(data, contract))
        os.utime(target, (1, 1))
        config = build / "config.json"
        config.write_text(json.dumps(dict(units=[dict(name=contract["unit"],
                                                     autogenerated=True, object=str(raw))])))
        contract_path = build / "contract.json"
        contract_path.write_text(json.dumps(contract))
        return build, raw, target, config, contract_path, data

    def run_tool(self, build, contract):
        return subprocess.run([sys.executable, "tools/normalize_text_storage_v3.py",
                               str(build), "--contract", str(contract)],
                              capture_output=True)

    def test_unchanged_copy_finishes_changed_split(self):
        with tempfile.TemporaryDirectory() as directory:
            build, raw, target, config, contract, data = self.prepare(directory)
            copied = target.read_bytes()
            self.assertLess(target.stat().st_mtime_ns, config.stat().st_mtime_ns)
            result = self.run_tool(build, contract)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertGreaterEqual(target.stat().st_mtime_ns, config.stat().st_mtime_ns)
            self.assertEqual(target.read_bytes(), copied)
            self.assertEqual(raw.read_bytes(), data)

    def test_rejected_input_never_completes_output(self):
        with tempfile.TemporaryDirectory() as directory:
            build, raw, target, config, contract, data = self.prepare(directory)
            raw.write_bytes(data + b"changed")
            copied, timestamp = target.read_bytes(), target.stat().st_mtime_ns
            result = self.run_tool(build, contract)
            self.assertNotEqual(result.returncode, 0)
            self.assertEqual(target.read_bytes(), copied)
            self.assertEqual(target.stat().st_mtime_ns, timestamp)
            self.assertEqual(raw.read_bytes(), data + b"changed")
